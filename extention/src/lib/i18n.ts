import { additionalMessages } from './translations';

const clockText: Record<Exclude<Locale, 'en' | 'fa'>, [string, string]> = {
  fr: ['Horloge et date', 'Paramètres du widget'], de: ['Uhr und Datum', 'Widget-Einstellungen'], tr: ['Saat ve tarih', 'Bileşen ayarları'], ar: ['الساعة والتاريخ', 'إعدادات الأداة'], hi: ['घड़ी और तारीख', 'विजेट सेटिंग्स'], zh: ['时钟与日期', '组件设置'], ja: ['時計と日付', 'ウィジェット設定'], ko: ['시계와 날짜', '위젯 설정'],
};
export const messages: Record<Locale, Record<MessageKey, string>> = { en, fa, ...Object.fromEntries(Object.entries(additionalMessages).map(([locale, words]) => [locale, { ...en, ...words, 'widget.clock': clockText[locale as keyof typeof clockText][0], 'widget.settings': clockText[locale as keyof typeof clockText][1] }])) } as Record<Locale, Record<MessageKey, string>>;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = messages[locale][key] ?? messages.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, formatNumber(locale, v));
  return s;
}

export function formatNumber(locale: Locale, v: string | number): string {
  return typeof v === 'number' ? new Intl.NumberFormat(LOCALE_META[locale].intl).format(v) : v;
}

export function detectLocale(): Locale {
  return 'en';
}
